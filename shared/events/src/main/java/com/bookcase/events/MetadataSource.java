package com.bookcase.events;

/**
 * Откуда взялось значение поля.
 *
 * <p>Порядок перечисления — это и порядок доверия: то, что нашлось в самом файле, надёжнее
 * угаданного из имени, а сказанное человеком не отменяется ничем. Источник хранится у каждого поля
 * отдельно, поэтому уточнение из интернета может дописать пустое название и не тронуть год, который
 * пользователь исправил руками.
 */
public enum MetadataSource {

    /** Метаданные внутри самого файла. */
    EMBEDDED,

    /** Разобранное имя файла — единственный источник для форматов без метаданных. */
    FILENAME,

    /** Внешний справочник. */
    EXTERNAL,

    /** Правка пользователя. */
    USER
}
