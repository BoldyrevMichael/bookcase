package com.bookcase.storage.config;

import org.springframework.context.annotation.Configuration;
import org.springframework.security.config.annotation.method.configuration.EnableMethodSecurity;

/**
 * Права на обложки.
 *
 * <p>Читать обложки может тот, кто вошёл, — как и всё остальное в сервисе. Соблазн открыть их
 * совсем был: обложку опубликовал внешний справочник, она одинакова у всех, у кого есть эта книга,
 * и личными данными не является. Но открытый адрес превращается в способ проверить чужую
 * библиотеку: имя объекта — хэш содержимого, а его может посчитать кто угодно, скачав ту же
 * картинку у справочника. Ответ «есть» или «нет» на такой запрос сообщает, лежит ли эта книга в
 * библиотеке, — а весь сервис построен на обратном: на чужую книгу мы отвечаем 404, чтобы даже факт
 * её существования не подтверждался.
 *
 * <p>Показу картинок в браузере это не мешает: страницу открывают по сессионной cookie, и тег
 * изображения отправляет её сам. Отдельный пропуск, как у скачивания книги, здесь не нужен —
 * пропуск нужен там, где по ссылке ходят вне страницы: переходом, скриптом, менеджером загрузок.
 *
 * <p>Запись сверх входа требует роли. У обложки нет владельца, а значит нет и защиты «это моё»: без
 * роли любой вошедший мог бы наполнять общую корзину чем угодно. Роль выдана служебной учётной
 * записи уточнителя — единственного, кто ходит в интернет; появится второй такой потребитель — ему
 * выдадут ту же роль, не трогая код. Проверка стоит на самом методе, ради неё здесь и включена
 * проверка прав по аннотациям.
 */
@Configuration
@EnableMethodSecurity
public class CoverSecurityConfig {}
