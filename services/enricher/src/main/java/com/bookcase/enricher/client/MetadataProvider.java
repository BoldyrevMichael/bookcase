package com.bookcase.enricher.client;

import java.util.Optional;

/**
 * Внешний справочник книг.
 *
 * <p>Справочники спрашиваются по очереди и независимо: у каждого своя область, где он силён.
 * Проверка на корпусе показала это наглядно — Google Books знает русские издания, которых у Open
 * Library нет вовсе, а Open Library находит то, о чём молчит Google. Поэтому второй спрашивается не
 * «когда первый сломался», а «когда первый не нашёл».
 */
public interface MetadataProvider {

    /** Имя справочника: попадает в карточку и в журнал, чтобы было видно, откуда данные. */
    String name();

    /** Работает ли справочник сейчас: без ключа или при выключенной настройке — нет. */
    boolean available();

    /**
     * Спрашивает справочник о книге.
     *
     * @return найденное или пусто, если справочник ничего не предложил
     */
    Optional<Candidate> find(Lookup lookup);
}
