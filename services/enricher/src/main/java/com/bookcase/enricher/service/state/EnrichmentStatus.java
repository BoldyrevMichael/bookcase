package com.bookcase.enricher.service.state;

/**
 * Состояние задачи уточнения.
 *
 * <p>«Не нашлось» и «не смогли спросить» разведены намеренно. Первое — законченный ответ:
 * справочник ответил, книги у него нет, и повторять запрос до его пополнения бессмысленно. Второе —
 * временная неудача, из-за которой попытку нужно отложить и сделать снова.
 */
public enum EnrichmentStatus {

    /** Ждёт своей очереди. */
    WAITING,

    /** Карточка дополнена. */
    DONE,

    /** Справочники ответили, но такой книги не знают. */
    NOT_FOUND,

    /** Спросить не удалось за все отведённые попытки. */
    GAVE_UP
}
